from collections.abc import AsyncIterator
from contextlib import AbstractAsyncContextManager
from typing import Protocol
from uuid import UUID

from app.models.case import CaseSummary
from app.models.conversation import Conversation
from app.models.diagnostic import Diagnostic
from app.models.vehicle import Vehicle


class Repository(Protocol):
    """Operations share a transaction; services own its boundary."""

    async def list_vehicles(self) -> list[Vehicle]: ...
    async def get_vehicle(self, vehicle_id: UUID, *, lock: bool = False) -> Vehicle | None: ...
    async def save_vehicle(self, vehicle: Vehicle) -> None: ...
    async def get_conversation(
        self, conversation_id: UUID, *, lock: bool = False, allow_closed: bool = False
    ) -> Conversation | None: ...
    async def list_cases(self, vehicle_id: UUID) -> list[CaseSummary]: ...
    async def save_conversation(self, conversation: Conversation) -> None: ...
    async def get_diagnostic(self, diagnostic_id: UUID) -> Diagnostic | None: ...
    async def save_diagnostic(self, diagnostic: Diagnostic) -> None: ...


class Store(Protocol):
    persistence: str

    def transaction(self) -> AbstractAsyncContextManager[Repository]: ...
    async def initialize(self) -> None: ...
    async def ready(self) -> bool: ...
    async def close(self) -> None: ...


# Used for type annotations on async context manager implementations.
Transaction = AsyncIterator[Repository]
